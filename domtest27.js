function open(c) {
  const errors = [];
  const vc = new VirtualConsole(); vc.on("jsdomError", (e) => errors.push(e.message));
  const dom = new JSDOM(html, { runScripts: "dangerously", url: "https://x.github.io/Daily-Flight-Card/", pretendToBeVisual: true, virtualConsole: vc,
    beforeParse(w) {
      if (c) w.localStorage.setItem("daily-flight-card", typeof c === "string" ? c : JSON.stringify(c));
      w.navigator.canShare = () => true;
      let shared = null;
      w.navigator.share = async (d) => { shared = d.files[0]; };
      w.__shared = () => shared;
    } });
  const w = dom.window, d = w.document;
  const q = (s) => d.querySelector(s), qa = (s) => [...d.querySelectorAll(s)];
  const click = (el) => el.dispatchEvent(new w.MouseEvent("click", { bubbles: true, cancelable: true }));
  const btn = (t) => qa("button").find((b) => b.textContent.trim() === t);
  const tab = (t) => [...q("[data-tabbar]").children].find((b) => b.textContent.trim() === t);
  const setter = Object.getOwnPropertyDescriptor(w.HTMLInputElement.prototype, "value").set;
  const type = async (el, v) => { setter.call(el, v); el.dispatchEvent(new w.Event("input", { bubbles: true })); await sleep(40); };
  const saved = () => JSON.parse(w.localStorage.getItem("daily-flight-card"));
  const shared = async () => { const f = w.__shared(); return f ? Buffer.from(await f.arrayBuffer()).toString("latin1") : null; };
  // the DUTIES page
  const sec = (k) => q(`[data-duty-sec="${k}"]`);
  const toggle = (k) => click(q(`[data-duty-toggle="${k}"]`));
  const item = (id) => q(`[data-duty="${id}"]`);
  const box = (id) => item(id) && item(id).querySelector("button[aria-pressed]");
  const ticked = (id) => box(id) && box(id).getAttribute("aria-pressed") === "true";
  const tick = async (id) => { click(box(id)); await sleep(60); };
  const count = (k) => q(`[data-duty-toggle="${k}"] [data-duty-count]`).textContent.trim();
  const handover = () => (q("[data-duty-handover]") ? q("[data-duty-handover]").textContent.trim() : null);
  const tags = (k) => [...sec(k).querySelectorAll("[data-duty-tag]")].map((t) => t.textContent.trim());
  return { w, d, q, qa, click, btn, tab, type, saved, shared, sec, toggle, item, box, ticked, tick, count, handover, tags, errors };
}

// The PDF's text strings, in order; a DUTIES line wrapped by splitTextToSize is joined back up.
function dutiesSection(bytes) {
  const strs = [...bytes.matchAll(/\(((?:\\.|[^\\)])*)\) Tj/g)].map((m) => m[1].replace(/\\(.)/g, "$1"));
  const a = strs.indexOf("DUTIES DONE");
  if (a < 0) return { strs, lines: null };
  const out = ["DUTIES DONE"];
  for (const s of strs.slice(a + 1)) {
    if (s === "MISC" || s.startsWith("GENERATED BY")) break;
    if (/^[A-Z]+: /.test(s)) out.push(s);
    else out[out.length - 1] += " " + s;
  }
  return { strs, lines: out };
}

